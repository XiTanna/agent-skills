#!/bin/bash
# Bulk electrolyte builder for GROMACS (packmol -> editconf -> steep minimisation -> <T>K run folder).
#
#   bulk_electrolyte.sh build  <workdir> <T> <box_nm> "<name>=<mol>:<n>,<mol>:<n>,..." [more specs]
#   bulk_electrolyte.sh submit <workdir> <T> <name> [<name> ...]
#
# <workdir> holds   basicfile/pdb/<mol>.pdb   basicfile/FF/{ffatomtype.itp,<mol>.itp}
#                   (optional, copied into the case when present: mixgro.sh mixgrosteep.sh grompp_min_ele_3dc.mdp
#                    and, for `submit`, gmx.job grompp_npt.mdp; otherwise the templates in ../assets are used)
# Result per case:  <workdir>/<name>/{mixgro,mixgrosteep,<T>K}   (<T>K holds min.gro index.ndx topol.top FF/)
# Environment:      GMX_BIN      (optional) bin dir of a plain GROMACS; gmx and packmol must otherwise be on PATH.
#                                Do NOT use a CPM-patched gmx build: it needs CPM_ControlFile.dat.
#                   ACCOUNT      Slurm account       (submit)
#                   PARTITION    Slurm partition     (submit)
#                   GMX_SETUP    shell line(s) that load GROMACS inside the job, e.g. "module load gromacs" or "source /path/GMXRC" (submit)
#                   Run from an interactive login shell (`bash -ic`) so modules/libraries are found and inherited by sbatch.
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ASSETS=$HERE/../assets
[ -n "${GMX_BIN:-}" ] && export PATH="$GMX_BIN:$PATH"
for t in gmx packmol bc; do command -v $t >/dev/null || { echo "$t not found on PATH"; exit 1; }; done

pick() { [ -f "$1/$2" ] && echo "$1/$2" || echo "$ASSETS/$2"; }   # template: user's copy in <workdir>/basicfile or <workdir>, else skill asset

cmd=${1:-}; W=${2:-}; T=${3:-}
[ -n "$cmd" ] && [ -d "$W" ] && [ -n "$T" ] || { sed -n 2,14p "$0"; exit 1; }
W=$(cd "$W" && pwd); BF=$W/basicfile
shift 3

if [ "$cmd" = build ]; then
  BOX=$1; shift
  for spec in "$@"; do
    name=${spec%%=*}; list=${spec#*=}
    D=$W/$name
    [ -e "$D" ] && { echo "$name exists, skip (delete the folder to rebuild)"; continue; }
    IFS=',' read -ra items <<< "$list"
    mols=(); nums=(); tot=0
    for it in "${items[@]}"; do mols+=("${it%%:*}"); nums+=("${it##*:}"); done
    for i in "${!mols[@]}"; do
      [ -f "$BF/pdb/${mols[$i]}.pdb" ] && [ -f "$BF/FF/${mols[$i]}.itp" ] || { echo "missing pdb/itp for ${mols[$i]}"; continue 2; }
      na=$(grep -c -E '^(ATOM|HETATM)' "$BF/pdb/${mols[$i]}.pdb"); tot=$(( tot + na*nums[$i] ))
    done
    echo "=== $name: $list -> $tot atoms, box $BOX nm, $T K"
    mkdir -p "$D/mixgro" "$D/mixgrosteep" "$D/${T}K"
    # ---- packmol + editconf
    for m in "${mols[@]}"; do cp "$BF/pdb/$m.pdb" "$D/mixgro/"; done
    sed "s/^lx=.*/lx=$BOX/; s/^ly=.*/ly=$BOX/; s/^lz=.*/lz=$BOX/" "$(pick $BF mixgro.sh)" > "$D/mixgro/mixgro.sh"
    A=$(echo "$BOX*10" | bc)
    { echo "tolerance 2.1"; echo "filetype pdb"; echo "output mixture.pdb"; echo
      for i in "${!mols[@]}"; do
        echo "structure ${mols[$i]}.pdb"; echo "  number ${nums[$i]}"; echo "  inside box 0. 0. 0. $A $A $A"; echo "end structure"; echo
      done; } > "$D/mixgro/mixture.inp"
    (cd "$D/mixgro" && sh mixgro.sh > mixgro.log 2>&1)
    [ -f "$D/mixgro/mixture.gro" ] || { echo "packmol/editconf FAILED for $name (see $name/mixgro/mixgro.log)"; continue; }
    # ---- topology + steepest descent
    cp "$D/mixgro/mixture.gro" "$D/mixgrosteep/"
    cp "$(pick $BF mixgrosteep.sh)" "$D/mixgrosteep/mixgrosteep.sh"
    cp "$(pick $BF grompp_min_ele_3dc.mdp)" "$D/mixgrosteep/grompp_min_ele_3dc.mdp"
    mkdir -p "$D/mixgrosteep/FF"; cp "$BF/FF/ffatomtype.itp" "$D/mixgrosteep/FF/"
    for m in "${mols[@]}"; do   # keep only the FIRST [ moleculetype ] of each species itp (stray extra blocks, e.g. an unused 'Na1', break grompp)
      awk '/^\[ *moleculetype/{k++} k<=1' "$BF/FF/$m.itp" > "$D/mixgrosteep/FF/$m.itp"
    done
    { echo "; topology generated by bulk_electrolyte.sh"; echo '#include "FF/ffatomtype.itp"'
      for m in "${mols[@]}"; do echo "#include \"FF/$m.itp\""; done
      echo; echo "[ system ]"; echo "system"; echo; echo "[ molecules ]"
      for i in "${!mols[@]}"; do echo "${mols[$i]} ${nums[$i]}"; done; } > "$D/mixgrosteep/topol.top"
    # log is NOT called min.*: mixgrosteep.sh runs `rm -rf min.*`
    (cd "$D/mixgrosteep" && sh mixgrosteep.sh > steep.log 2>&1)
    [ -f "$D/mixgrosteep/min.gro" ] || { echo "minimisation FAILED for $name:"; grep -A3 -E '^(ERROR|Fatal)' "$D/mixgrosteep/steep.log" | head -12; continue; }
    cp "$D/mixgrosteep/min.gro" "$D/mixgrosteep/index.ndx" "$D/mixgrosteep/topol.top" "$D/${T}K/"; cp -r "$D/mixgrosteep/FF" "$D/${T}K/"
    echo "$name: $(sed -n 2p "$D/${T}K/min.gro") atoms, box $(tail -1 "$D/${T}K/min.gro")"
    grep -E 'converged|Potential Energy|Maximum force' "$D/mixgrosteep/steep.log" | tail -3
    grep -i -E 'total charge|non-zero' "$D/mixgrosteep/steep.log" | head -2
  done

elif [ "$cmd" = submit ]; then
  : "${ACCOUNT:?set ACCOUNT}" "${PARTITION:?set PARTITION}" "${GMX_SETUP:?set GMX_SETUP}"
  for name in "$@"; do
    R=$W/$name/${T}K; [ -f "$R/min.gro" ] || { echo "$name: no $R/min.gro"; continue; }
    cp "$(pick $W gmx.job)" "$R/gmx.job"; cp "$(pick $W grompp_npt.mdp)" "$R/grompp_npt.mdp"
    sed -i "s/^#SBATCH --job-name=.*/#SBATCH --job-name=$name-${T}K/; s/^#SBATCH -A .*/#SBATCH -A $ACCOUNT/; s/^#SBATCH -p .*/#SBATCH -p $PARTITION/" "$R/gmx.job"
    GMX_SETUP="$GMX_SETUP" awk '{ if ($0 == "#GMX_ENV_SETUP#") print ENVIRON["GMX_SETUP"]; else print }' "$R/gmx.job" > "$R/gmx.job.tmp" && mv "$R/gmx.job.tmp" "$R/gmx.job"
    sed -i -E "s/^(ref_t *= *)[0-9.]+/\1$T/; s/^(gen_temp *= *)[0-9.]+/\1$T/" "$R/grompp_npt.mdp"
    (cd "$R" && sbatch gmx.job)     # run this script via `bash -ic` so the job inherits the interactive environment
  done
else
  sed -n 2,14p "$0"; exit 1
fi
